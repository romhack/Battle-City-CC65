#define TANK_DIR_UP         0x00
#define TANK_DIR_LEFT       0x01
#define TANK_DIR_DOWN       0x02
#define TANK_DIR_RIGHT      0x03

// Macros to get/set fields
#define GET_TANK_CMD(tank_id)       ((tank_status[tank_id] & 0xF0) >> 4)
#define GET_TANK_DIR(tank_id)       (tank_status[tank_id] & 0x03)
#define GET_RESPAWN_FRAME(tank_id)  ((tank_status[tank_id] & 0x06) >> 1)

#define SET_TANK_CMD(tank_id, cmd)  (tank_status[tank_id] = (tank_status[tank_id] & 0x0F) | (cmd))
#define SET_TANK_DIR(tank_id, dir)  (tank_status[tank_id] = (tank_status[tank_id] & 0xFC) | (dir))
#define SET_TANK_STATUS(tank_id, cmd, dir) (tank_status[tank_id] = (cmd) | (dir))

