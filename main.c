// Handle stage number changes
static void change_stage(signed char delta) {
    FRAME_CNT = 0;
    stage_number += delta;
    
    // Clamp to valid range
    if (stage_number < STAGE_MIN) {
        stage_number = STAGE_MIN;
    }
    if (stage_number > STAGE_MAX) {
        stage_number = STAGE_MAX;
    }
}

