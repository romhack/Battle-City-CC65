// Handle input for stage selection. True, if start pressed, False otherwise
static unsigned char handle_stage_input(void) {
    pad1 = pad_trigger(0);
    
    if (pad1 & PAD_START) {
        return 1;  // Exit loop
    }
    
    // A button: increment (press or hold)
    if (pad1 & PAD_A) {
        change_stage(1);
        return 0;
    }
    
    if ((pad_state(0) & PAD_A) && ((FRAME_CNT & 7) == 0)) {
        change_stage(1);
        return 0;
    }
    
    // B button: decrement (press or hold)
    if (pad1 & PAD_B) {
        change_stage(-1);
        return 0;
    }
    
    if ((pad_state(0) & PAD_B) && ((FRAME_CNT & 7) == 0)) {
        change_stage(-1);
        return 0;
    }
    
    return 0;  
}

GameState stage_select_loop(void) {
    init_stage_select_vars();

    oam_clear();
    ppu_wait_nmi();
    vram_adr(NAMETABLE_A);
    scroll(0, 0);
    set_bg_pal_number(4);    

    draw_converging_shutters();

    while (1) {
        ppu_wait_nmi();
        draw_stage_display();
        
        if (skip_stage_select_flag) {
            return STATE_GAMEPLAY;
        }
        
        if (handle_stage_input()) {
            return STATE_STAGE_START; 
        }
    }
}

//copy tsa block to dst
static void draw_tsa(unsigned char idx) {
    memcpy(dst, tsa_data + (idx << 2), 2);
    memcpy(dst + SCREEN_COLS, (tsa_data + 2) + (idx << 2), 2);
}


static void write_tsa_attrib(unsigned char x, unsigned char y, unsigned char tsa_id)
{
    static const unsigned char tsa_pal[16] = {
    0, 0, 0, 0, 0, 3, 3, 3, 3, 3, 1, 2, 3, 0, 0, 0};
    static const unsigned char attr_mask[4] = {0xFC,0xF3,0xCF,0x3F};
    unsigned char pal;

    pal = tsa_pal[tsa_id];
    k = attr_mask[(y & 2) | ((x & 2) >> 1)];
    i = ((y << 1) & 0xF8) + (x >> 2);
    pal |= pal << 2;
    pal |= pal << 4;
    SCREEN_BUFFER[0x3C0 + i] =  (SCREEN_BUFFER[0x3C0 + i] & k) | (pal & ~k);
}

//Load stage data to screen buffer. Number to be set in global stage_number
void load_stage(void) {
    unsigned char tile_x, tile_y;
    i = stage_number;
    src = (unsigned char *)levels;
    while (--i) {
        src += LEVEL_BYTES;
    }

    dst = SCREEN_BUFFER + COORD_TO_NT_OFFSET(FRAME_OFFSET, FRAME_OFFSET);
    tile_y = FRAME_OFFSET;
    for (j = 0; j < LEVEL_ROWS; ++j) {
        tile_x = FRAME_OFFSET;
        for (cnt = 0; cnt < LEVEL_COLS; cnt += 2) {
            temp = *src++;
            //left tsa
            draw_tsa(temp >> 4);
            dst += 2;
            tile_x = FRAME_OFFSET + (cnt<<1);
            write_tsa_attrib(tile_x, tile_y, temp >> 4);
            //right tsa
            if (cnt < LEVEL_COLS - 1) {
                draw_tsa(temp & 0x0F);
                dst += 2;
                write_tsa_attrib (tile_x + 2, tile_y, temp & 0x0F);                
            }
            tile_x += 4;
        }
        tile_y += 2;
        dst += (SCREEN_COLS - LEVEL_COLS) * 2;
    }
    //Copy unpacked attributes to VRAM, so during diverging shutters stage will be shown in correct attributes
    add_vram_cpy_cmd(NAMETABLE_A + 0x3C0, SCREEN_BUFFER + 0x3C0, 0x40);
    
}

//Draw curtain open effect copying level from screen buffer to VRAM. (diverging from middle towards top and bottom)
static void draw_diverging_shutters(void) {
    static unsigned char top_row, bot_row;
    
    for (temp = 0xF; temp != 0xFF; --temp) {
        ppu_wait_nmi();
        
        // top row (counting down from middle to top)
        top_row = temp;
        add_vram_cpy_cmd(
            NAMETABLE_A + COORD_TO_NT_OFFSET(FRAME_OFFSET, top_row),
            SCREEN_BUFFER + COORD_TO_NT_OFFSET(FRAME_OFFSET, top_row),
            26
        );
        
        // mirrored bottom row
        bot_row = 0x1D - temp;
        add_vram_cpy_cmd(
            NAMETABLE_A + COORD_TO_NT_OFFSET(FRAME_OFFSET, bot_row),
            SCREEN_BUFFER + COORD_TO_NT_OFFSET(FRAME_OFFSET, bot_row),
            26
        );
    }
}
